def prereq_text(code):
    d = D.get(code)
    return d['prereq'] if d else None

def prereq_phrase(code):
    txt = prereq_text(code)
    if not txt:
        return None
    label, body = [x.strip() for x in txt.split(':', 1)]
    codes = re.findall(r'\d{8}', body)
    if label == 'วิชาที่ต้องเรียนมาก่อน' and body == codes[0] and len(codes) == 1:
        return f"ต้องเรียนวิชา {ref(codes[0])} มาก่อน"
    if label == 'วิชาที่ต้องเรียนมาก่อน' and len(codes) == 1 and body == f'{codes[0]} หรือพร้อมกัน':
        return f"ต้องเรียนวิชา {ref(codes[0])} มาก่อน หรือเรียนพร้อมกันกับวิชานี้ได้"
    if label == 'วิชาที่ต้องเรียนมาก่อนหรือพร้อมกัน' and len(codes) == 1 and body == codes[0]:
        return f"ต้องเรียนวิชา {ref(codes[0])} มาก่อนหรือเรียนพร้อมกัน"
    names = ' และ '.join(ref(c) for c in codes)
    return f"มีเงื่อนไขตามคำอธิบายรายวิชาว่า \"{txt}\" ซึ่งเกี่ยวข้องกับวิชา {names}"

