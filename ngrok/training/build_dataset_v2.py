# ---------------------------------------------------------------- plans
def plan_of(name):
    return PR if name == 'regular' else PC

def where(code, plan):
    for (y, s), v in plan.items():
        for it in v['items']:
            if it['code'] == code:
                return (y, s)
    return None

def sem_items(plan, y, s):
    return plan[(y, s)]['items']

def sem_total(plan, y, s):
    return plan[(y, s)]['total']

def item_line(it):
    cr = cnum(it['credit'])
    if it['code']:
        return f"- {it['code']} {it['name']} ({cr} หน่วยกิต)"
    return f"- {it['name']} ({cr} หน่วยกิต)"

def sem_block(plan, y, s):
    return '\n'.join(item_line(it) for it in sem_items(plan, y, s))

def same_sem(y, s):
    a = [(i['code'], i['name'], i['credit']) for i in sem_items(PR, y, s)]
    b = [(i['code'], i['name'], i['credit']) for i in sem_items(PC, y, s)]
    return a == b and sem_total(PR, y, s) == sem_total(PC, y, s)

