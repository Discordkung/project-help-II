def type_of_hours(c):
    h = hours(c)
    if not h:
        return None
    b, p, st = h
    if p == 0:
        return 'บรรยาย'
    if b == 0:
        return 'ปฏิบัติการ'
    return 'บรรยายและปฏิบัติการ'

