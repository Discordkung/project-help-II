def clean_th(s):
    s = re.sub(r'(?<=[ก-ฮ]) (?=[ะาำิีึืุูั็่้๊๋์])', '', s)
    return re.sub(r'\s+', ' ', s).strip()

def clean_en(s):
    return re.sub(r'\s+', ' ', s).strip()

def cnum(c):
    return re.match(r'^(\d+(?:-\d+)?)', c).group(1)

def hours(c):
    m = re.match(r'^\d+\((\d+)-(\d+)-(\d+)\)$', c)
    return tuple(int(x) for x in m.groups()) if m else None

