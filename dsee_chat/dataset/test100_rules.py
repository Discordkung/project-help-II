# ================================================================== รันทดสอบ
def check_gpa_case(resp, spec):
    _, pairs = spec[0], spec[1]
    must_sub = spec[2] if len(spec) > 2 else None
    if resp is None:
        return False
    expected = reference_gpa(pairs)
    m = re.search(r"เกรดเฉลี่ย\s*=\s*([\d.]+)", resp)
    if expected is None:
        ok = m is None  # ไม่ควรคำนวณได้เลย
    else:
        ok = bool(m) and abs(float(m.group(1)) - expected) < 0.005
    if ok and must_sub:
        ok = must_sub in resp
    return ok


