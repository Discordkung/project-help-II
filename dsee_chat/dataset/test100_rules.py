# ---------------------------------------------------------------- ข้อมูลอ้างอิงสำหรับคำนวณ GPA อย่างอิสระ
INDEX = json.load(open(os.path.join(BACKEND, "rag_index.json"), encoding="utf-8"))
BY_CODE = {c["code"]: c for c in INDEX["courses"]}
GRADE_POINTS = {"A": 4.0, "B+": 3.5, "B": 3.0, "C+": 2.5, "C": 2.0, "D+": 1.5, "D": 1.0, "F": 0.0}


def _credit_of(code):
    d = BY_CODE.get(code)
    if not d:
        return None
    raw = d["text"].split("หน่วยกิต", 1)[1].split("(")[0].strip()
    try:
        return int(raw)
    except ValueError:
        return None


def reference_gpa(pairs):
    """คำนวณ GPA อ้างอิง (เขียนแยกจาก dsee_core.py โดยตั้งใจ เพื่อตรวจสอบไขว้กัน)"""
    tc = tp = 0.0
    seen = set()
    for code, g in pairs:
        if code in seen or code not in BY_CODE:
            continue
        seen.add(code)
        cr = _credit_of(code)
        if cr is None:
            continue
        tc += cr
        tp += cr * GRADE_POINTS[g.upper()]
    if not tc:
        return None
    return float(f"{tp / tc:.2f}")  # จัดรูปแบบแบบเดียวกับ dsee_core.py (f'{gpa:.2f}') ไม่ใช้ round() เฉยๆ เพราะปัดเลขต่างกันได้


