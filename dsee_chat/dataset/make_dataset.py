def noisy(q):
    r = random.random()
    if r < 0.12:
        return q.replace(" ", "")
    if r < 0.22:
        return q + random.choice(["ครับ", "คะ", "ค่ะ", " ครับผม", " หน่อย", "?", " จ้า"])
    return q


